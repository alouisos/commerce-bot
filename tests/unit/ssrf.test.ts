import { describe, expect, it } from "vitest";
import { isBlockedAddress } from "@/lib/crawl/ssrf";

describe("isBlockedAddress", () => {
  it.each([
    "127.0.0.1", "127.8.8.8", "10.0.0.1", "172.16.0.1", "172.31.255.255", "192.168.1.1", "169.254.169.254",
    "100.64.0.1", "100.127.255.255", "0.0.0.0", "0.1.2.3", "224.0.0.1", "239.1.1.1", "240.0.0.1", "255.255.255.255",
    "::1", "::", "fe80::1", "febf::1", "fc00::1", "fd12:3456::1", "ff02::1",
    "::ffff:127.0.0.1", "::ffff:10.0.0.1", "::ffff:7f00:1", "::ffff:a9fe:a9fe", "::ffff:192.168.0.1", "[::1]", "nonsense",
  ])("blocks %s", (ip) => expect(isBlockedAddress(ip)).toBe(true));
  it.each([
    "8.8.8.8", "1.1.1.1", "93.184.216.34", "172.15.0.1", "172.32.0.1", "100.63.0.1", "100.128.0.1", "169.253.1.1",
    "223.255.255.255", "2606:4700:4700::1111", "2001:db8::1", "::ffff:8.8.8.8", "::ffff:808:808",
  ])("allows %s", (ip) => expect(isBlockedAddress(ip)).toBe(false));
});
